export function generateMetadata({
  params,
}: LocalePageProps): Promise<Metadata> {
  return localePageMetadata(params, '/docs/cli', (copy) => ({
    title: copy.docs.metaTitleCli,
    description: copy.docs.metaDescriptionCli,
  }))
}

/** motir-core's own CLI reference — the authority beyond this page. */
const CLI_REFERENCE_URL =
  'https://github.com/motir-co/motir-core/blob/main/docs/cli.md'

/*
 * THE PROSE LIVES IN `content/docs/cli/<locale>.md` (MOTIR-8035). This file keeps
 * what a reader copies (the three code panes), what is generated (the command
 * groups) and the values the prose must not restate (everything the catalogue
 * carries). The document's parts: `body` is the introduction, `meta` the
 * package line and `reference` every section from Install to the end. Its
 * `unreachable` paragraph is never rendered: a built page has no request at
 * which the catalogue could be unreachable, and a failed read fails the build
 * (`lib/docs.ts`, MOTIR-10645).
 */

function Command({
  command,
  locale,
}: {
  command: CliCommandsDocument['commands'][number]
  locale: Locale
}) {
  // What `motir --help` prints is English wherever the page is not (MOTIR-8049);
  // the invocation and flags are code and need no marking.
  const generatedLang = locale === DEFAULT_LOCALE ? undefined : 'en'
  return (
    <li className="py-4">
      <code className="font-(family-name:--font-mono) text-[13.5px] font-semibold text-(--el-text)">
        {command.invocation}
      </code>
      <p
        lang={generatedLang}
        className="mt-1 max-w-[68ch] text-[13px] leading-relaxed text-(--el-text-secondary)"
      >
        {command.description}
      </p>
      {command.options.length > 0 ? (
        <dl className="mt-2 grid grid-cols-[minmax(0,14rem)_1fr] gap-x-4 gap-y-1.5">
          {command.options.map((option) => (
            <div key={option.flags} className="contents">
              <dt className="font-(family-name:--font-mono) text-[12.5px] text-(--el-text)">
                {option.flags}
              </dt>
              <dd
                lang={generatedLang}
                className="m-0 min-w-0 text-[12.5px] leading-relaxed text-(--el-text-secondary)"
              >
                {option.description}
              </dd>
            </div>
          ))}
        </dl>
      ) : null}
    </li>
  )
}

export default async function CliPage({ params }: LocalePageProps) {
  const locale = await enterLocale(params)
  const copy = await getCopy(locale)
  const labels = {
    sandboxPage: copy.docs.sandbox,
    mcpPage: copy.docs.mcp,
    apiPage: copy.docs.api,
    cliReferenceUrl: CLI_REFERENCE_URL,
  }
  const heading = (
    <h1 className="font-(family-name:--font-serif) text-[30px] leading-[1.2] font-bold tracking-[-0.01em] text-(--el-text)">
      {copy.docs.cli}
    </h1>
  )

  const catalogue = await fetchCliCommands()
  const groups = groupCliCommands(catalogue)
  const ownDocument = resolveDocsDocument('cli', locale).fallback === null
  const { parts, note } = await renderDocsParts({
    slug: 'cli',
    locale,
    slots: {
      install: (
        <div className="mt-3">
          <CodeBlock
            caption="install"
            code={`${catalogue.installCommand}\n\n# or, without installing:\nnpx ${catalogue.packageName} --help`}
          />
        </div>
      ),
      authenticate: (
        <div className="mt-3">
          <CodeBlock
            caption="authenticate"
            code={`motir login\n\n# or with a token you already hold:\nmotir auth login --server ${catalogue.defaultServer} --token <pat>\n\n# or from the environment:\nexport MOTIR_SERVER=${catalogue.defaultServer}\nexport MOTIR_TOKEN=<pat>`}
          />
        </div>
      ),
      'link-and-check': (
        <div className="mt-3">
          <CodeBlock
            caption="link and check"
            code={`motir link --project ACME\nmotir doctor`}
          />
        </div>
      ),
      commands: [
        // Panel E: withheld while the page's own document is the English fallback.
        ownDocument ? (
          <GeneratedReferenceNote
            key="note"
            source="cli"
            locale={locale}
            copy={copy}
          />
        ) : null,
        ...groups.map((group) => (
          <section key={group.heading} className="mt-7">
            <h3 className="text-[11px] font-semibold tracking-wide text-(--el-text-secondary) uppercase">
              {group.heading}
            </h3>
            <ul className="mt-2 flex flex-col divide-y divide-(--el-border) border-y border-(--el-border)">
              {group.commands.map((command) => (
                <Command key={command.path} command={command} locale={locale} />
              ))}
            </ul>
          </section>
        )),
      ],
    },
    values: {
      // Nodes, not strings: a catalogue value is never parsed as Markdown.
      packageName: <>{catalogue.packageName}</>,
      packageVersion: <>{catalogue.packageVersion}</>,
      commandCount: <>{catalogue.commandCount}</>,
      nodeRequirement: <>{catalogue.nodeRequirement}</>,
      defaultServer: (
        <code className="rounded-(--radius-kbd) bg-(--el-muted) px-1.5 py-0.5 font-(family-name:--font-mono) text-[13px]">
          {catalogue.defaultServer}
        </code>
      ),
      ...labels,
    },
  })

  return (
    <>
      {heading}
      {note}
      {parts.meta}
      {parts.body}
      {parts.reference}
    </>
  )
}
